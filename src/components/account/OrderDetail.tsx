"use client";
import Link from "next/link";
import { ArrowLeft, ArrowRight, FastForward, RotateCcw, X } from "lucide-react";
import { useState } from "react";
import { AddressBlock, OrderItemsList, OrderStatusBadge, OrderTimeline } from "@/components/account/OrderParts";
import { PriceSummary } from "@/components/commerce/PriceSummary";
import { Button, LinkButton } from "@/components/ui/Button";
import { Radio, Select } from "@/components/ui/Form";
import { Overlay, OverlayBody, OverlayFooter, OverlayHeader } from "@/components/ui/Overlay";
import { SimulatedNotice, SimulatedTag } from "@/components/ui/Simulated";
import { EmptyState } from "@/components/ui/States";
import { Skeleton } from "@/components/ui/Skeleton";
import { fmtDate, fmtDateLong } from "@/lib/format";
import { STATUS_LABEL, canCancel, canReturn, nextStatus } from "@/lib/orders";
import { advanceOrder, cancelOrder, requestReturn, useAuth } from "@/stores/account";
import { toast } from "@/stores/ui";

const CANCEL_REASONS = ["Ordered by mistake", "Found a better price elsewhere", "Delivery is taking too long", "Want to change size or colour", "Other"];
const RETURN_REASONS = ["Doesn’t fit", "Not as pictured", "Quality isn’t what I expected", "Received the wrong item", "Changed my mind"];

export function OrderDetail({ id }: { id: string }) {
  const { ready, orders } = useAuth();
  const order = orders.find((o) => o.id === id);
  const [dialog, setDialog] = useState<"cancel" | "return" | null>(null);
  const [reason, setReason] = useState("");

  if (!ready) return <div role="status" aria-label="Loading order"><Skeleton className="h-8 w-64" /><Skeleton className="mt-8 h-64 w-full" /></div>;
  if (!order) {
    return <EmptyState title="We can’t find that order" text="It may belong to another account, or this browser’s data was reset." actions={<LinkButton href="/account/orders" size="lg">All orders</LinkButton>} className="py-14" />;
  }
  const next = nextStatus(order.status);

  const open = (d: "cancel" | "return") => (setReason(d === "cancel" ? CANCEL_REASONS[0] : RETURN_REASONS[0]), setDialog(d));
  const finished = ["delivered", "cancelled", "refunded"].includes(order.status);

  return (
    <div>
      <Link href="/account/orders" className="tap mb-6 inline-flex items-center gap-2 text-[13px] text-ink-2 hover:text-ink"><ArrowLeft size={15} aria-hidden /> All orders</Link>
      <header className="flex flex-wrap items-end justify-between gap-x-6 gap-y-4 border-b border-ink pb-6">
        <div>
          <p className="eyebrow text-ink-3">Order</p>
          <h2 className="display-md mt-3 tabular-nums">{order.number}</h2>
          <p className="mt-2 text-[13.5px] text-ink-3">Placed {fmtDate(order.placedAt, { day: "numeric", month: "short", year: "numeric" })}</p>
        </div>
        <OrderStatusBadge status={order.status} />
      </header>
      <SimulatedNotice className="mt-6">Simulated order — tracking updates are generated by the prototype, not a courier.</SimulatedNotice>

      <section aria-labelledby="trk" className="mt-8 border border-ink bg-paper p-6 sm:p-8">
        <div className="mb-8 flex flex-wrap items-start justify-between gap-4">
          <div>
            <h3 id="trk" className="display-xs">Tracking</h3>
            {!finished && <p className="mt-1.5 text-[13.5px] text-ink-2">Estimated delivery <strong className="font-medium text-ink">{fmtDateLong(order.eta)}</strong></p>}
          </div>
          {next && (
            <div className="flex items-center gap-2">
              <SimulatedTag note="Moves the order to its next state so you can review each stage of tracking." />
              <Button variant="secondary" size="sm" icon={<FastForward size={13} />} onClick={() => (advanceOrder(order.id), toast({ title: `Order ${STATUS_LABEL[next].toLowerCase()}`, description: "Simulated status change." }))}>
                Simulate: {STATUS_LABEL[next].toLowerCase()}
              </Button>
            </div>
          )}
        </div>
        <OrderTimeline order={order} rail />
        {order.returnReason && <p className="mt-6 border-t border-line pt-4 text-[13.5px] text-ink-2">Return reason: {order.returnReason}</p>}
      </section>

      {/* items 5 + summary 4 of the 9 content columns (7 + 5 of 12 on tablets) */}
      <div className="mt-12 grid grid-cols-1 gap-x-[var(--gap)] gap-y-12 sm:grid-cols-12 lg:grid-cols-9">
        <div className="sm:col-span-7 lg:col-span-5">
          <section aria-labelledby="its">
            <h3 id="its" className="display-xs mb-5">Items</h3>
            <OrderItemsList order={order} />
          </section>
          <div className="mt-8 flex flex-wrap gap-3">
            {canCancel(order.status) && <Button variant="danger" icon={<X size={15} />} onClick={() => open("cancel")}>Cancel order</Button>}
            {canReturn(order.status) && <Button variant="secondary" icon={<RotateCcw size={15} />} onClick={() => open("return")}>Request a return</Button>}
            <Link href="/edits" className="link-u tap inline-flex h-11 items-center gap-2 text-[12px] font-semibold uppercase tracking-[0.09em]">Keep shopping <ArrowRight size={14} aria-hidden /></Link>
          </div>
        </div>

        <aside className="space-y-6 sm:col-span-5 lg:col-span-4">
          <section aria-labelledby="dl" className="border border-line bg-paper p-6">
            <h3 id="dl" className="mb-3 text-[15px] font-medium">Delivery address</h3>
            <AddressBlock a={order.address} />
            <p className="mt-3 text-[12.5px] capitalize text-ink-3">{order.delivery} delivery</p>
            <h3 className="mb-2 mt-6 text-[15px] font-medium">Payment</h3>
            <p className="text-[14px] text-ink-2">{order.payment.detail} <span className="text-ink-3">(simulated)</span></p>
          </section>
          <section aria-labelledby="ps" className="border border-line bg-paper p-6">
            <h3 id="ps" className="mb-3 text-[15px] font-medium">Payment summary</h3>
            <PriceSummary b={order.pricing} />
          </section>
        </aside>
      </div>

      <Overlay open={dialog !== null} onClose={() => setDialog(null)} label={dialog === "cancel" ? "Cancel order" : "Request a return"} side="center" panelClassName="sm:w-[min(94vw,520px)]">
        <OverlayHeader title={dialog === "cancel" ? "Cancel this order?" : "Request a return"} sub={order.number} />
        <OverlayBody>
          {dialog === "cancel" ? (
            <div role="radiogroup" aria-label="Reason for cancelling" className="grid grid-cols-1 gap-2.5">
              {CANCEL_REASONS.map((r) => (<Radio key={r} name="cancel-reason" checked={reason === r} onChange={() => setReason(r)} label={r} />))}
            </div>
          ) : (
            <Select label="Why are you returning it?" value={reason} onChange={(e) => setReason(e.target.value)}>
              {RETURN_REASONS.map((r) => (<option key={r}>{r}</option>))}
            </Select>
          )}
        </OverlayBody>
        <OverlayFooter className="grid grid-cols-2 gap-3">
          <Button variant="ghost" size="lg" onClick={() => setDialog(null)}>Keep order</Button>
          <Button variant={dialog === "cancel" ? "danger" : "primary"} size="lg" onClick={() => {
            if (dialog === "cancel") { cancelOrder(order.id); toast({ title: "Order cancelled", description: "Simulated — nothing was charged." }); }
            else { requestReturn(order.id, reason); toast({ title: "Return requested", description: "Simulated pickup will be scheduled." }); }
            setDialog(null);
          }}>{dialog === "cancel" ? "Cancel order" : "Submit request"}</Button>
        </OverlayFooter>
      </Overlay>
    </div>
  );
}
